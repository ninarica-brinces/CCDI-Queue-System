CREATE INDEX IF NOT EXISTS queue_tickets_service_lane_status_order_idx
    ON public.queue_tickets (service_date, lane, status, created_at, ticket_id);

CREATE INDEX IF NOT EXISTS queue_tickets_student_active_lookup_idx
    ON public.queue_tickets (service_date, student_id, status)
    WHERE student_id IS NOT NULL;

-- 2. DAILY REPORTS TABLE (Clean PostgreSQL Version)
CREATE TABLE IF NOT EXISTS public.daily_reports (
    report_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date date NOT NULL,
    total_tickets integer NOT NULL,
    completed_tickets integer NOT NULL,
    cancelled_tickets integer NOT NULL,
    waiting_tickets integer NOT NULL,
    serving_tickets integer NOT NULL,
    regular_tickets integer NOT NULL,
    priority_tickets integer NOT NULL,
    service_breakdown jsonb NOT NULL DEFAULT '{}'::jsonb,
    lane_breakdown jsonb NOT NULL DEFAULT '{}'::jsonb,
    status_breakdown jsonb NOT NULL DEFAULT '{}'::jsonb,
    archived_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS daily_reports_report_date_idx
    ON public.daily_reports (report_date, archived_at);

-- 3. CCDI STUDENTS TABLE
CREATE TABLE IF NOT EXISTS public.ccdi_students (
    student_id varchar(20) PRIMARY KEY,
    first_name varchar(50) NOT NULL,
    last_name varchar(50) NOT NULL,
    address varchar(150) NOT NULL,
    course varchar(20) NOT NULL,
    year_level integer NOT NULL,
    tuition_total decimal(10, 2) NOT NULL,
    tuition_paid decimal(10, 2) NOT NULL,
    registration_date date NOT NULL
);

