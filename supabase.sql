CREATE TABLE IF NOT EXISTS public.queue_tickets (
    ticket_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number text NOT NULL,
    lane text NOT NULL,
    student_name text NOT NULL,
    transaction_type text NOT NULL,
    payment_method text NOT NULL,
    status text NOT NULL DEFAULT 'waiting',
    service_date date NOT NULL DEFAULT CURRENT_DATE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamptz
);

ALTER TABLE public.queue_tickets
    ADD COLUMN IF NOT EXISTS student_id text;

CREATE INDEX IF NOT EXISTS queue_tickets_service_lane_status_order_idx
    ON public.queue_tickets (service_date, lane, status, created_at, ticket_id);

CREATE UNIQUE INDEX IF NOT EXISTS queue_tickets_one_active_student_per_day_idx
    ON public.queue_tickets (service_date, student_id)
    WHERE student_id IS NOT NULL AND status IN ('waiting', 'serving');
